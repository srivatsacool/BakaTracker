/**
 * PixelIcon — the SINGLE application entry point for Pixelarticons.
 *
 * Per Refinement Master Pack (ASSETS.md / DESIGN.md §5) Pixelarticons is the
 * PRIMARY personality/navigation icon system. This abstraction:
 *   - maps a curated semantic `name` → the installed React component
 *   - co-locates the icon policy in one file (no scattered pixelarticons imports)
 *   - forwards standard SVG props (size, color, className, title/aria)
 *   - keeps Lucide as the UTILITY layer (close, chevron, drag, etc. live there)
 *
 * To add a new icon: extend `PIXEL_ICONS` with the imported component. The
 * mapping is intentionally explicit (not a dynamic `icons[name]`) so tree-
 * shaking works and missing icons fail loudly at build time, not runtime.
 */
export type PixelIconName = keyof typeof PIXEL_ICONS;

