export interface PixelIconProps extends React.SVGProps<SVGSVGElement> {
  name: PixelIconName;
  /** pixel size in px (default 20) */
  size?: number;
  /** filled color; defaults to currentColor */
  color?: string;
  title?: string;
}

export const PixelIcon: React.FC<PixelIconProps> = ({
  name,
  size = 20,
  color,
  title,
  className,
  ...props
}) => {
  const Icon = PIXEL_ICONS[name];
  if (!Icon) {
    if (import.meta.env?.DEV) {
      console.warn(`[PixelIcon] unknown icon name: "${name}"`);
    }
    return null;
  }
  return (
    <Icon
      width={size}
      height={size}
      color={color}
      className={className}
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      {...props}
    />
  );
};

PixelIcon.displayName = 'PixelIcon';

export { PIXEL_ICONS };
